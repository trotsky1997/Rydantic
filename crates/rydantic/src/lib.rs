#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TypeKind {
    String,
    Number,
    Boolean,
    Array,
    Object,
    Any,
}

/// Extension point for JSON-compatible Rust types.
///
/// A decoder must record an error whenever it returns None. It may return a
/// constructed value together with constraint errors; public entry points reject it.
pub trait JsonType: Sized {
    fn decode(value: Value, ctx: &mut Context, coerce: bool) -> Option<Self>;
    fn encode(&self, ctx: &mut Context) -> Value;
    /// Representation using input aliases and including output-excluded fields.
    /// Used to validate typed defaults without losing required input information.
    fn encode_input(&self, ctx: &mut Context) -> Value {
        self.encode(ctx)
    }
    fn schema(ctx: &mut SchemaContext, coerce: bool) -> Value;
    fn validate_into(&self, _ctx: &mut Context) {}
    fn missing() -> Option<Self> {
        None
    }
    fn allows_missing() -> bool {
        false
    }
    fn kind() -> TypeKind {
        TypeKind::Any
    }
}

/// Marker traits make invalid attribute/type combinations fail during compilation.
pub trait StringType: JsonType {}
pub trait NumericType: JsonType {}
pub trait LengthType: JsonType {}

/// High-level model API generated by `#[derive(Model)]`.
pub trait Model: JsonType {
    /// Strict by default. Explicit field-level `coerce` is applied by the derive.
    fn parse_json(input: &str) -> Result<Self, ValidationErrors> {
        let value = serde_json::from_str(input).map_err(|error| {
            ValidationErrors::from(
                ValidationError::new("json_invalid", error.to_string())
                    .with_stage(Stage::Parse)
                    .with_param("line", error.line())
                    .with_param("column", error.column()),
            )
        })?;
        Self::parse_value(value)
    }
    fn parse_value(value: Value) -> Result<Self, ValidationErrors> {
        let mut ctx = Context::new();
        let model = Self::decode(value, &mut ctx, false);
        ctx.finish(model)
    }
    /// Recheck a value constructed or mutated in Rust. Does not normalize it.
    fn validate(&self) -> Result<(), ValidationErrors> {
        let mut ctx = Context::new();
        self.validate_into(&mut ctx);
        ctx.result()
    }
    /// Revalidate before serialization, including fields excluded from the output.
    fn dump(&self) -> Result<Value, ValidationErrors> {
        self.validate()?;
        let mut ctx = Context::new();
        let value = self.encode(&mut ctx);
        ctx.finish(Some(value))
    }
    fn dump_json(&self) -> Result<String, ValidationErrors> {
        let value = self.dump()?;
        serde_json::to_string(&value).map_err(|error| {
            ValidationError::new("serialization", error.to_string())
                .with_stage(Stage::Serialize)
                .into()
        })
    }
    fn json_schema(mode: SchemaMode) -> Value {
        let mut ctx = SchemaContext::new(mode);
        let root = Self::schema(&mut ctx, false);
        ctx.finish(root)
    }
    fn schema_report(mode: SchemaMode) -> SchemaReport {
        SchemaReport::new(Self::json_schema(mode))
    }
    fn parse_validated_json(input: &str) -> Result<Validated<Self>, ValidationErrors> {
        Self::parse_json(input).map(Validated)
    }
}

/// Read-only access to a successfully checked model. No DerefMut or unchecked constructor.
/// Interior-mutability types can weaken this guarantee; their JsonType implementation
/// must document that behavior.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Validated<T: Model>(T);
impl<T: Model> Validated<T> {
    pub fn new(value: T) -> Result<Self, ValidationErrors> {
        value.validate()?;
        Ok(Self(value))
    }
    pub fn get(&self) -> &T {
        &self.0
    }
    pub fn into_inner(self) -> T {
        self.0
    }
}
impl<T: Model> std::ops::Deref for Validated<T> {
    type Target = T;
    fn deref(&self) -> &T {
        &self.0
    }
}
impl<T: Model> serde::Serialize for Validated<T> {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        let value = self.0.dump().map_err(serde::ser::Error::custom)?;
        serde::Serialize::serialize(&value, serializer)
    }
}
impl<'de, T: Model> serde::Deserialize<'de> for Validated<T> {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value = <Value as serde::Deserialize>::deserialize(deserializer)?;
        T::parse_value(value)
            .map(Self)
            .map_err(serde::de::Error::custom)
    }
}

