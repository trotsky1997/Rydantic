#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TypeKind {
    String,
    Number,
    Boolean,
    Array,
    Object,
    Any,
    Decimal,
}

/// Extension point for JSON-compatible Rust types.
///
/// A decoder must record an error whenever it returns None. It may return a
/// constructed value together with constraint errors; public entry points reject it.
pub trait JsonType: Sized {
    fn decode(value: Value, ctx: &mut Context, coerce: bool) -> Option<Self>;
    /// Decode a raw subtree. Custom types can override this to bypass Value entirely.
    fn decode_input(input: Input<'_>, ctx: &mut Context, coerce: bool) -> Option<Self> {
        Self::decode(input.into_value(ctx)?, ctx, coerce)
    }
    fn encode(&self, ctx: &mut Context) -> Value;
    /// Representation using input aliases and including output-excluded fields.
    /// Used to validate typed defaults without losing required input information.
    fn encode_input(&self, ctx: &mut Context) -> Value {
        self.encode(ctx)
    }
    fn schema(ctx: &mut SchemaContext, coerce: bool) -> Value;
    fn validate_into(&self, _ctx: &mut Context) {}
    fn normalize(self, rules: &rules::Rules, ctx: &mut Context) -> Option<Self> {
        if !rules.normalizes() {
            return Some(self);
        }
        let mut value = self.encode_input(ctx);
        rules.prepare(&mut value);
        Self::decode(value, ctx, false)
    }
    fn validate_rules(&self, rules: &rules::Rules, ctx: &mut Context) {
        rules.validate(&self.encode(ctx), ctx);
    }
    fn async_required(_seen: &mut std::collections::HashSet<&'static str>) -> bool {
        false
    }
    fn missing() -> Option<Self> {
        None
    }
    fn allows_missing() -> bool {
        false
    }
    fn kind() -> TypeKind {
        TypeKind::Any
    }
}

