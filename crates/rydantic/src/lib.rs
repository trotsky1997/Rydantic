//! Unified JSON models for Rust.
//!
//! ```
//! use rydantic::{Model, SchemaMode};
//!
//! #[derive(Debug, Model)]
//! struct User {
//!     #[model(trim, min_length = 3)]
//!     name: String,
//!     #[model(ge = 18, le = 120)]
//!     age: u8,
//! }
//!
//! let user = User::parse_json(r#"{"name":" Alice ","age":25}"#)?;
//! assert_eq!(user.name, "Alice");
//! assert!(User::json_schema(SchemaMode::Output).is_object());
//! # Ok::<(), rydantic::ValidationErrors>(())
//! ```

