//! Fail-closed JSON Schema 2020-12 subset to Rydantic Rust source.
//!
//! This unpublished developer tool deliberately rejects optional properties,
//! unbounded numbers, external references and unsupported assertion keywords.
use serde_json::{Map, Value};
use std::{collections::BTreeSet, fmt};

pub const MAX_SCHEMA_BYTES: usize = 65_536;
const MAX_NODES: usize = 256;
const MAX_DEPTH: usize = 32;
const DIALECT: &str = "https://json-schema.org/draft/2020-12/schema";

/// A schema JSON Pointer (empty means root) and a non-input-bearing explanation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Error {
    pub pointer: String,
    pub message: &'static str,
}
impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "{}: {}",
            if self.pointer.is_empty() {
                "#"
            } else {
                &self.pointer
            },
            self.message
        )
    }
}
impl std::error::Error for Error {}
fn error(pointer: &str, message: &'static str) -> Error {
    Error {
        pointer: pointer.into(),
        message,
    }
}
fn at(pointer: &str, key: &str) -> String {
    format!("{}/{}", pointer, key.replace('~', "~0").replace('/', "~1"))
}
fn check_member_name(name: &str, pointer: &str) -> Result<(), Error> {
    if [
        "$serde_json::private::Number",
        "$serde_json::private::RawValue",
    ]
    .contains(&name)
    {
        return Err(error(
            pointer,
            "serde_json reserved member names are unsupported",
        ));
    }
    Ok(())
}
fn sorted(object: &Map<String, Value>) -> Vec<(&String, &Value)> {
    let mut entries: Vec<_> = object.iter().collect();
    entries.sort_by(|a, b| a.0.cmp(b.0));
    entries
}
// Rust debug strings, unlike JSON string escaping, are Rust literals (including
// control characters). No schema text is interpolated as Rust syntax.
fn literal(value: &str) -> String {
    format!("{value:?}")
}

/// Generate one module's contents with a public `RootModel` entry point.
///
/// Identifiers are stable positional names, never schema-controlled code.
/// Objects require `additionalProperties: false` and every property required.
/// Only direct `#/$defs/name` references are accepted, with no recursion.
pub fn generate(schema: &Value) -> Result<String, Error> {
    // Bound traversal before serialization, including programmatically built
    // Values deeper than serde_json's input parser would accept.
    fn preflight(value: &Value, depth: usize, budget: &mut usize) -> Result<(), Error> {
        if depth > 128 || *budget == 0 {
            return Err(error("", "schema JSON traversal exceeds depth/node limit"));
        }
        *budget -= 1;
        match value {
            Value::Array(values) => {
                for value in values {
                    preflight(value, depth + 1, budget)?;
                }
            }
            Value::Object(values) => {
                for value in values.values() {
                    preflight(value, depth + 1, budget)?;
                }
            }
            _ => {}
        }
        Ok(())
    }
    preflight(schema, 0, &mut 8192)?;
    struct SizeLimit(usize);
    impl std::io::Write for SizeLimit {
        fn write(&mut self, bytes: &[u8]) -> std::io::Result<usize> {
            self.0 = self.0.saturating_add(bytes.len());
            if self.0 > MAX_SCHEMA_BYTES {
                return Err(std::io::Error::other("schema too large"));
            }
            Ok(bytes.len())
        }
        fn flush(&mut self) -> std::io::Result<()> {
            Ok(())
        }
    }
    serde_json::to_writer(SizeLimit(0), schema)
        .map_err(|_| error("", "schema exceeds 65536 bytes"))?;
    let mut generator = Generator {
        root: schema,
        next: 0,
        definitions: Vec::new(),
        visiting: BTreeSet::new(),
    };
    let root = schema
        .as_object()
        .ok_or_else(|| error("", "schema must be an object"))?;
    if let Some(dialect) = root.get("$schema") {
        if dialect.as_str() != Some(DIALECT) {
            return Err(error("/$schema", "only JSON Schema 2020-12 is supported"));
        }
    }
    if let Some(defs) = root.get("$defs") {
        let defs = defs
            .as_object()
            .ok_or_else(|| error("/$defs", "$defs must be an object"))?;
        // Check even unused definitions, rather than hiding unsupported schemas.
        for (key, schema) in sorted(defs) {
            check_member_name(key, &at("/$defs", key))?;
            generator.node(schema, &at("/$defs", key), 0, None)?;
        }
    }
    generator.node(schema, "", 0, Some("RootModel"))?;
    Ok(format!("// Generated by rydantic-codegen; do not edit.\n// Requires rydantic with its derive feature.\n{}", generator.definitions.join("\n")))
}
struct Generator<'a> {
    root: &'a Value,
    next: usize,
    definitions: Vec<String>,
    visiting: BTreeSet<String>,
}
impl Generator<'_> {
    fn node(
        &mut self,
        schema: &Value,
        pointer: &str,
        depth: usize,
        name: Option<&str>,
    ) -> Result<String, Error> {
        if depth > MAX_DEPTH || self.next >= MAX_NODES {
            return Err(error(pointer, "schema expansion exceeds depth/node limit"));
        }
        let id = self.next;
        self.next += 1;
        let name = name
            .map(str::to_owned)
            .unwrap_or_else(|| format!("SchemaNode{id}"));
        let object = schema
            .as_object()
            .ok_or_else(|| error(pointer, "boolean schemas are not supported"))?;
        for keyword in ["title", "description"] {
            if object.get(keyword).is_some_and(|v| !v.is_string()) {
                return Err(error(&at(pointer, keyword), "annotation must be a string"));
            }
        }
        if let Some(reference) = object.get("$ref") {
            self.keys(object, pointer, &["$ref"])?;
            let reference = reference
                .as_str()
                .ok_or_else(|| error(&at(pointer, "$ref"), "$ref must be a string"))?;
            let encoded = reference.strip_prefix("#/$defs/").ok_or_else(|| {
                error(
                    &at(pointer, "$ref"),
                    "only local $defs references are supported",
                )
            })?;
            if encoded.contains('/') || encoded.contains('%') || encoded.is_empty() {
                return Err(error(
                    &at(pointer, "$ref"),
                    "reference must target one $defs entry",
                ));
            }
            let key = encoded.replace("~1", "/").replace("~0", "~");
            if key.replace('~', "~0").replace('/', "~1") != encoded {
                return Err(error(&at(pointer, "$ref"), "invalid JSON Pointer escape"));
            }
            let target = at("/$defs", &key);
            if !self.visiting.insert(target.clone()) {
                return Err(error(
                    &at(pointer, "$ref"),
                    "recursive references are unsupported",
                ));
            }
            let value = self
                .root
                .get("$defs")
                .and_then(|v| v.get(&key))
                .ok_or_else(|| error(&at(pointer, "$ref"), "reference target does not exist"))?
                .clone();
            let ty = self.node(&value, &target, depth + 1, Some(&name))?;
            self.visiting.remove(&target);
            return Ok(ty);
        }
        if let Some(types) = object.get("type").and_then(Value::as_array) {
            if types.len() != 2 || types.iter().filter(|v| v.as_str() == Some("null")).count() != 1
            {
                return Err(error(
                    &at(pointer, "type"),
                    "only one type plus null is supported",
                ));
            }
            if object.contains_key("enum") {
                return Err(error(
                    &at(pointer, "enum"),
                    "nullable enums are unsupported",
                ));
            }
            let ty = types.iter().find(|v| v.as_str() != Some("null")).unwrap();
            if !ty.is_string() {
                return Err(error(&at(pointer, "type"), "type entries must be strings"));
            }
            let mut nonnull = object.clone();
            nonnull.insert("type".into(), ty.clone());
            let inner = self.node(&Value::Object(nonnull), pointer, depth + 1, None)?;
            self.definitions.push(format!(
                "#[derive(Debug, rydantic::Model)]\npub struct {name}(pub Option<{inner}>);\n"
            ));
            return Ok(name);
        }
        let ty = object
            .get("type")
            .and_then(Value::as_str)
            .ok_or_else(|| error(&at(pointer, "type"), "explicit supported type is required"))?;
        let body = match ty {
            "object" => {
                self.keys(
                    object,
                    pointer,
                    &["type", "properties", "required", "additionalProperties"],
                )?;
                if object.get("additionalProperties") != Some(&Value::Bool(false)) {
                    return Err(error(
                        &at(pointer, "additionalProperties"),
                        "objects must explicitly forbid extra properties",
                    ));
                }
                let props = object
                    .get("properties")
                    .and_then(Value::as_object)
                    .ok_or_else(|| {
                        error(&at(pointer, "properties"), "properties must be an object")
                    })?;
                let required = object
                    .get("required")
                    .and_then(Value::as_array)
                    .ok_or_else(|| {
                        error(
                            &at(pointer, "required"),
                            "explicit required array is required",
                        )
                    })?;
                let mut names = BTreeSet::new();
                for (i, name) in required.iter().enumerate() {
                    let name = name.as_str().ok_or_else(|| {
                        error(
                            &at(&at(pointer, "required"), &i.to_string()),
                            "required entries must be strings",
                        )
                    })?;
                    if !names.insert(name) || !props.contains_key(name) {
                        return Err(error(
                            &at(pointer, "required"),
                            "duplicate or unknown required property",
                        ));
                    }
                }
                if names.len() != props.len() {
                    return Err(error(
                        &at(pointer, "required"),
                        "optional properties are unsupported; missing is not null",
                    ));
                }
                let mut fields = String::new();
                for (i, (key, value)) in sorted(props).into_iter().enumerate() {
                    check_member_name(key, &at(&at(pointer, "properties"), key))?;
                    let inner =
                        self.node(value, &at(&at(pointer, "properties"), key), depth + 1, None)?;
                    fields.push_str(&format!(
                        "    #[model(required, rename = {})]\n    pub field_{i}: {inner},\n",
                        literal(key)
                    ));
                }
                format!("pub struct {name} {{\n{fields}}}\n")
            }
            "string" if object.contains_key("enum") => {
                self.keys(object, pointer, &["type", "enum"])?;
                let values = object["enum"]
                    .as_array()
                    .filter(|v| !v.is_empty() && v.len() <= 64)
                    .ok_or_else(|| {
                        error(&at(pointer, "enum"), "enum must contain 1 to 64 strings")
                    })?;
                let mut seen = BTreeSet::new();
                let mut variants = String::new();
                for (i, value) in values.iter().enumerate() {
                    let value = value.as_str().ok_or_else(|| {
                        error(
                            &at(&at(pointer, "enum"), &i.to_string()),
                            "only string enums are supported",
                        )
                    })?;
                    if !seen.insert(value) {
                        return Err(error(
                            &at(pointer, "enum"),
                            "duplicate enum values are unsupported",
                        ));
                    }
                    variants.push_str(&format!(
                        "    #[model(rename = {})]\n    Variant{i},\n",
                        literal(value)
                    ));
                }
                format!("pub enum {name} {{\n{variants}}}\n")
            }
            "string" | "array" => {
                let (min, max, inner) = if ty == "array" {
                    self.keys(object, pointer, &["type", "items", "minItems", "maxItems"])?;
                    let item = object.get("items").ok_or_else(|| {
                        error(
                            &at(pointer, "items"),
                            "homogeneous items schema is required",
                        )
                    })?;
                    let item = self.node(item, &at(pointer, "items"), depth + 1, None)?;
                    ("minItems", "maxItems", format!("Vec<{item}>"))
                } else {
                    self.keys(object, pointer, &["type", "minLength", "maxLength"])?;
                    ("minLength", "maxLength", "String".into())
                };
                let mut attrs = Vec::new();
                let mut bounds = [None, None];
                for (i, (keyword, attr)) in [(min, "min_length"), (max, "max_length")]
                    .iter()
                    .enumerate()
                {
                    if let Some(value) = object.get(*keyword) {
                        let n = value
                            .as_u64()
                            .filter(|n| *n <= u32::MAX as u64)
                            .ok_or_else(|| {
                                error(
                                    &at(pointer, keyword),
                                    "length must be an unsigned 32-bit integer",
                                )
                            })?;
                        bounds[i] = Some(n);
                        attrs.push(format!("{attr} = {n}"));
                    }
                }
                if bounds[0].zip(bounds[1]).is_some_and(|(a, b)| a > b) {
                    return Err(error(
                        pointer,
                        "contradictory length bounds are unsupported",
                    ));
                }
                let attrs = if attrs.is_empty() {
                    String::new()
                } else {
                    format!("#[model({})] ", attrs.join(", "))
                };
                format!("pub struct {name}({attrs}pub {inner});\n")
            }
            "integer" => {
                self.keys(object, pointer, &["type", "minimum", "maximum"])?;
                let bound = |key| {
                    object.get(key).and_then(Value::as_i64).ok_or_else(|| {
                        error(
                            &at(pointer, key),
                            "integer requires explicit integral i64 minimum and maximum",
                        )
                    })
                };
                let min = bound("minimum")?;
                let max = bound("maximum")?;
                if min > max {
                    return Err(error(
                        pointer,
                        "contradictory numeric bounds are unsupported",
                    ));
                }
                format!(
                    "pub struct {name}(#[model(ge = {}, le = {})] pub i64);\n",
                    literal(&min.to_string()),
                    literal(&max.to_string())
                )
            }
            "boolean" | "null" => {
                self.keys(object, pointer, &["type"])?;
                if ty == "null" {
                    format!("pub struct {name};\n")
                } else {
                    format!("pub struct {name}(pub bool);\n")
                }
            }
            _ => {
                return Err(error(
                    &at(pointer, "type"),
                    "unsupported type; arbitrary numbers cannot be narrowed faithfully",
                ))
            }
        };
        self.definitions
            .push(format!("#[derive(Debug, rydantic::Model)]\n{body}"));
        Ok(name)
    }
    fn keys(
        &self,
        object: &Map<String, Value>,
        pointer: &str,
        allowed: &[&str],
    ) -> Result<(), Error> {
        for (key, _) in sorted(object) {
            if allowed.contains(&key.as_str())
                || ["title", "description"].contains(&key.as_str())
                || (pointer.is_empty() && ["$schema", "$defs"].contains(&key.as_str()))
            {
                continue;
            }
            return Err(error(&at(pointer, key), "unsupported keyword"));
        }
        Ok(())
    }
}
